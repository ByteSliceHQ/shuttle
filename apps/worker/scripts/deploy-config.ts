#!/usr/bin/env bun
/**
 * Writes `wrangler.deploy.jsonc`: `wrangler.jsonc` plus the built web app as static assets, so
 * the deployed Worker is the whole of Shuttle on one origin.
 *
 * It is a file of its own, made from the first, because the assets folder only exists after a
 * web build: declared in `wrangler.jsonc` itself it would stop `wrangler dev` on a fresh
 * checkout. `bun run deploy` builds the web app, runs this, and deploys with the result.
 *
 * Anything in `SHUTTLE_DEPLOY_VARS` (a JSON object) is merged over `vars`, which is how a
 * deployment sets its own `SHUTTLE_WEB_URL`, `SHUTTLE_WORKSPACE_MODE` and `SHUTTLE_PREVIEW_HOST`
 * without editing the file everyone develops against. What a deployment keeps there that this
 * config does not publish goes to `.prod.vars.json` for the deploy to apply as Worker secrets.
 * `SHUTTLE_DEPLOY_ROUTES` (a JSON array of wrangler routes) puts the deployment on its own domain
 * and takes it off `workers.dev`, so there is one address and one place a sign-in is good for.
 *
 * The container image is only built and pushed for a deployment whose sandboxes are Cloudflare
 * containers. On Daytona, or in memory, nothing uses it.
 */
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { z } from 'zod'

import { type DeployRoute, deploymentPreviewHost, splitDeployVars } from './deploy-config-lib'

const worker = join(dirname(fileURLToPath(import.meta.url)), '..')
const webDist = join(worker, '../web/dist')

if (!existsSync(join(webDist, 'index.html'))) {
  console.error('apps/web/dist is missing. Build the web app first: bun run --cwd apps/web build')
  process.exit(1)
}

function previewHost(
  current: string | undefined,
  routes: readonly DeployRoute[],
  mode: string | undefined,
): string {
  try {
    const host = deploymentPreviewHost(current, routes, mode)

    if (host !== current) {
      console.log(
        `SHUTTLE_PREVIEW_HOST is ${String(current)} in wrangler.jsonc; deploying previews under ${host}`,
      )
    }

    return host
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exit(1)
  }
}

const wranglerModule: unknown = await import(join(worker, 'wrangler.jsonc'))

const wranglerSchema = z.object({
  default: z.looseObject({
    vars: z.record(z.string(), z.string()),
    containers: z.array(z.unknown()).optional(),
  }),
})

const base = wranglerSchema.parse(wranglerModule).default
const deployVars: unknown = JSON.parse(process.env.SHUTTLE_DEPLOY_VARS ?? '{}')
const deployRoutes: unknown = JSON.parse(process.env.SHUTTLE_DEPLOY_ROUTES ?? '[]')
const overrides = z.record(z.string(), z.string()).parse(deployVars)
const routes = z.array(z.looseObject({ pattern: z.string() })).parse(deployRoutes)
const split = splitDeployVars(overrides)
const vars = { ...base.vars, ...split.vars }

vars.SHUTTLE_PREVIEW_HOST = previewHost(
  vars.SHUTTLE_PREVIEW_HOST,
  routes,
  vars.SHUTTLE_WORKSPACE_MODE,
)

const usesContainers = ['container', 'cloudflare'].includes(vars.SHUTTLE_WORKSPACE_MODE ?? '')
const { containers, ...rest } = base
const withRoutes = { ...rest, routes, workers_dev: false, preview_urls: false }
const routed = routes.length > 0 ? withRoutes : rest
const contained = usesContainers && containers !== undefined ? { ...routed, containers } : routed

const config = {
  ...contained,
  vars,
  assets: {
    directory: '../web/dist',
    binding: 'WEB',
    // Every app route is the same page; the page's router takes it from there.
    not_found_handling: 'single-page-application',
    // The Worker decides what is a page and what is the API. See `src/web-app.ts`.
    run_worker_first: true,
  },
}

const out = join(worker, 'wrangler.deploy.jsonc')
const secretsOut = join(worker, '.prod.vars.json')

writeFileSync(
  out,
  `// Generated by scripts/deploy-config.ts from wrangler.jsonc. Do not edit.\n${JSON.stringify(config, null, 2)}\n`,
)

writeFileSync(secretsOut, `${JSON.stringify(split.secrets, null, 2)}\n`, { mode: 0o600 })

console.log(`wrote ${out} (${Object.keys(vars).length} vars)`)
console.log(`wrote ${secretsOut} (${Object.keys(split.secrets).length} secrets)`)
