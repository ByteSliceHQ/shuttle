#!/usr/bin/env bun
/**
 * Writes `wrangler.deploy.jsonc`: `wrangler.jsonc` plus the built web app as static assets, so
 * the deployed Worker is the whole of Shuttle on one origin.
 *
 * It is a file of its own, made from the first, because the assets folder only exists after a
 * web build: declared in `wrangler.jsonc` itself it would stop `wrangler dev` on a fresh
 * checkout. `bun run deploy` builds the web app, runs this, and deploys with the result.
 *
 * Anything in `SHUTTLE_DEPLOY_VARS` (a JSON object) is merged over `vars`, which is how a
 * deployment sets its own `SHUTTLE_WEB_URL`, `SHUTTLE_WORKSPACE_MODE` and `SHUTTLE_PREVIEW_HOST`
 * without editing the file everyone develops against. `SHUTTLE_DEPLOY_ROUTES` (a JSON array of
 * wrangler routes) puts the deployment on its own domain and takes it off `workers.dev`, so
 * there is one address and one place a sign-in is good for.
 *
 * The container image is only built and pushed for a deployment whose sandboxes are Cloudflare
 * containers. On Daytona, or in memory, nothing uses it.
 */
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const worker = join(dirname(fileURLToPath(import.meta.url)), '..')
const webDist = join(worker, '../web/dist')

if (!existsSync(join(webDist, 'index.html'))) {
  console.error('apps/web/dist is missing. Build the web app first: bun run --cwd apps/web build')
  process.exit(1)
}

const base = (await import(join(worker, 'wrangler.jsonc'))).default as Record<string, unknown>
const overrides = JSON.parse(process.env.SHUTTLE_DEPLOY_VARS ?? '{}') as Record<string, string>

const routes = JSON.parse(process.env.SHUTTLE_DEPLOY_ROUTES ?? '[]') as unknown[]
const vars = { ...(base.vars as Record<string, string>), ...overrides }
const usesContainers = ['container', 'cloudflare'].includes(vars.SHUTTLE_WORKSPACE_MODE ?? '')
const { containers, ...rest } = base

const config = {
  ...rest,
  ...(usesContainers && containers ? { containers } : {}),
  ...(routes.length > 0 ? { routes, workers_dev: false, preview_urls: false } : {}),
  vars,
  assets: {
    directory: '../web/dist',
    binding: 'WEB',
    // Every app route is the same page; the page's router takes it from there.
    not_found_handling: 'single-page-application',
    // The Worker decides what is a page and what is the API. See `src/web-app.ts`.
    run_worker_first: true,
  },
}

const out = join(worker, 'wrangler.deploy.jsonc')

writeFileSync(
  out,
  `// Generated by scripts/deploy-config.ts from wrangler.jsonc. Do not edit.\n${JSON.stringify(config, null, 2)}\n`,
)

console.log(`wrote ${out}`)
